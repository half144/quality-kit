// The strict quality-kit preset: what project instructions ask for in prose
// becomes a lint error. Everything is "error" (a warning blocks nothing and
// just piles up). The debt from when the ruleset was adopted stays frozen in
// the baseline, which only shrinks.
//
// Extracted from Flock (eslint.quality.js), without the rules that only apply
// there. A project's own rules come in through `lint-extra.cjs` in the ruleset folder.

