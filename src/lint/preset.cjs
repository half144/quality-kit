// Well-known hacks: forcing order with setTimeout 0, winning specificity with
// important, switching off the type system with `as unknown as`.
const RESTRICTED_SYNTAX = [
  ...[
    "CallExpression[callee.name='setTimeout'][arguments.length=1]",
    "CallExpression[callee.name='setTimeout'][arguments.1.value=0]",
    "CallExpression[callee.property.name='setTimeout'][arguments.1.value=0]",
  ].map((selector) => ({ selector, message: "setTimeout with a 0 delay is a hack: resolve the ordering with the platform's official mechanism." })),
  ...["JSXAttribute[name.name='className'] Literal[value=/(^|\\s)![\\w\\[-]|[\\w\\]]!(\\s|$)/]", "Literal[value=/!\\s*important/]"].map((selector) => ({
    selector,
    message: "Forcing style priority (important) is a hack: fix the specificity at the source.",
  })),
  { selector: "TSAsExpression > TSAsExpression[typeAnnotation.type='TSUnknownKeyword']", message: "`as unknown as` switches off the type: fix the type at the source." },
];

